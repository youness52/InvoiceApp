object AppStrings {
    operator fun get(language: AppLanguage): StringsDefinition {
        return when (language) {
            AppLanguage.FR -> FrenchStrings
            AppLanguage.AR -> ArabicStrings
            AppLanguage.EN -> EnglishStrings
        }
    }

    fun getStatusLabel(status: InvoiceStatus, language: AppLanguage): String {
        val s = get(language)
        return when (status) {
